"""Export authored 1.1 enemy rules from a bounded read-only declaration audit.

This is an offline inventory, not an activation predictor or a game controller.
"""
import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path)
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--fixture", required=True, type=Path)
    parser.add_argument("--header", type=Path, help="Generate the native reviewed display registry")
    args = parser.parse_args()
    raw = args.snapshot.read_bytes()
    data = json.loads(raw)
    enemies = defaultdict(list)
    for declaration in data["declarations"]:
        path = declaration["name"].split("/")
        if len(path) < 4 or path[:2] != ["syncdeath", "playervsai"]:
            continue
        enemies[path[2]]
        for animation in declaration["animations"]:
            state = animation["state"]
            if state.startswith("kill_") and 2 in declaration["inputs"]:
                action = "GK"
            elif 16 in declaration["inputs"]:
                action = "CS"
            else:
                continue
            enemies[path[2]].append(dict(
                declaration=declaration["name"], state=state, action=action,
                groups=declaration["groups"], quadrants=declaration["focal"],
                ranges=declaration["ranges"], pitchYaw=declaration["pitchYaw"],
                centric=declaration["centric"], inputs=declaration["inputs"],
            ))
    catalog = dict(
        scope="Loaded retail 1.1 authored declarations; aliases, state, equipment and final selection are separate.",
        source_sha256=hashlib.sha256(raw).hexdigest(),
        source_pid=data["pid"], enemies=dict(sorted(enemies.items())),
    )
    args.catalog.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    rows = ["# monster state action quadrants groups minXY maxXY minZ maxZ pitch yaw centric[5] declaration"]
    for enemy, rules in catalog["enemies"].items():
        for rule in rules:
            row = [enemy, rule["state"], rule["action"], rule["quadrants"], "|".join(rule["groups"]) or "-",
                   *rule["ranges"], *rule["pitchYaw"], *rule["centric"], rule["declaration"]]
            rows.append("\t".join(map(str, row)))
    args.fixture.write_text("\n".join(rows) + "\n", encoding="utf-8")
    if args.header:
        labels = dict(arachnotron="Arachnotron", archvile="Archvile", baron="Baron", buffpod="Buff Pod",
                      cacodemon="Cacodemon", carcass="Carcass", doomhunter="Doom Hunter", dreadknight="Dread Knight",
                      gargoyle="Gargoyle", gladiator="Gladiator", hellknight="Hell Knight", imp="Imp",
                      mancubus_fire="Mancubus", marauder="Marauder", painelemental="Pain Elemental", pinky="Pinky",
                      prowler="Prowler", revenant="Revenant", soldier_blaster="Soldier / Blaster", tentacle="Tentacle",
                      tyrant="Tyrant", whiplash="Whiplash", zombie_maykr="Maykr Zombie",
                      zombie_tier1="Zombie tier 1", zombie_tier3="Zombie tier 3")
        header = ["#pragma once", "// Generated by Tools/audit-sync-rules.py; do not infer rules from animation names.",
                  "// Source SHA256: " + catalog["source_sha256"],
                  "struct SyncAuditedEnemyRule {const char* declaration;const char* animation;const char* family;const char* label;int action;uint32_t quadrants;const char* groups;};",
                  "static constexpr SyncAuditedEnemyRule syncAuditedEnemyRules[]{"]
        for enemy, rules in catalog["enemies"].items():
            for rule in rules:
                strings = [rule["declaration"], rule["state"], enemy, labels[enemy]]
                header.append("    {" + ",".join(json.dumps(s) for s in strings) + "," +
                              str(0 if rule["action"] == "GK" else 1) + "," + str(rule["quadrants"]) + "u," +
                              json.dumps("|".join(sorted(set(rule["groups"])))) + "},")
        header.append("};")
        args.header.write_text("\n".join(header) + "\n", encoding="utf-8")
    print(f"Authored inventory: {len(enemies)} enemy groups, "
          f"{sum(r['action'] == 'GK' for a in enemies.values() for r in a)} GK states, "
          f"{sum(r['action'] == 'CS' for a in enemies.values() for r in a)} Chainsaw states.")


if __name__ == "__main__":
    main()

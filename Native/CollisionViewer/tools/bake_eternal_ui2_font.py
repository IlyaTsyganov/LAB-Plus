"""Bake the real bundled Eternal UI 2 Regular face for the native overlay.

Development-only dependency: Pillow/FreeType. No font parser or rasterizer is
needed by LAB Plus at runtime. Run --verify to compare the checked-in header.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version, features

ROOT = Path(__file__).resolve().parents[3]
FONT = ROOT / "Assets/fonts/EternalUi2Regular.ttf"
HEADER = ROOT / "Native/CollisionViewer/src/eternal_ui2_font_data.h"
SIZE, WIDTH, HEIGHT, PADDING = 18, 256, 256, 2


def bake() -> tuple[str, Image.Image, dict]:
    font = ImageFont.truetype(str(FONT), SIZE, layout_engine=ImageFont.Layout.BASIC)
    assert font.getname() == ("Eternal UI 2", "Regular"), font.getname()
    atlas = Image.new("L", (WIDTH, HEIGHT), 0)
    glyphs = []
    x = y = PADDING
    shelf = 0
    for value in range(32, 127):
        char = chr(value)
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        if width and height:
            if x + width + PADDING > WIDTH:
                x, y, shelf = PADDING, y + shelf + PADDING * 2, 0
            assert y + height + PADDING <= HEIGHT, "Atlas overflow"
            mask = Image.new("L", (width, height))
            ImageDraw.Draw(mask).text((-left, -top), char, font=font, fill=255, anchor="ls")
            atlas.paste(mask, (x, y))
            atlas_x, atlas_y = x, y
            x += width + PADDING * 2
            shelf = max(shelf, height)
        else:
            atlas_x = atlas_y = width = height = 0
        glyphs.append((value, float(font.getlength(char)), left, top, width, height, atlas_x, atlas_y))
    data = atlas.tobytes()
    runs = [(len(list(group)), value) for value, group in itertools.groupby(data)]
    # A uint16 count is ample for these short transparent/coverage runs.
    assert all(0 < count <= 65535 for count, _ in runs)
    ascent, descent = font.getmetrics()
    font_hash = hashlib.sha256(FONT.read_bytes()).hexdigest()
    lines = [
        "#pragma once", "#include <array>", "#include <algorithm>", "#include <cstdint>",
        "// Generated by tools/bake_eternal_ui2_font.py; do not edit glyph data.",
        "// Source: Assets/fonts/EternalUi2Regular.ttf (Eternal UI 2 Regular).",
        f"// Pillow {pillow_version}; FreeType {features.version_module('freetype2')}; BASIC layout, {SIZE}px, exact 8-bit coverage.",
        f'inline constexpr char kEternalUi2SourceSha256[]="{font_hash}";',
        f"inline constexpr unsigned kEternalUi2AtlasWidth={WIDTH},kEternalUi2AtlasHeight={HEIGHT};",
        f"inline constexpr float kEternalUi2FontSize={SIZE}.f,kEternalUi2Ascent={ascent}.f,kEternalUi2Descent={descent}.f,kEternalUi2LineHeight={ascent+descent}.f;",
        "struct EternalUi2Glyph { float advance; int16_t left,top; uint16_t width,height,x,y; };",
        "inline constexpr std::array<EternalUi2Glyph,95> kEternalUi2Glyphs{{",
    ]
    for value, advance, left, top, width, height, atlas_x, atlas_y in glyphs:
        lines.append(f"    {{{advance:.6f}f,{left},{top},{width},{height},{atlas_x},{atlas_y}}}, // U+{value:04X}")
    lines += ["}};", "struct EternalUi2CoverageRun { uint16_t count; uint8_t value; };",
              f"inline constexpr std::array<EternalUi2CoverageRun,{len(runs)}> kEternalUi2CoverageRuns{{{{"]
    for offset in range(0, len(runs), 8):
        lines.append("    " + ",".join(f"{{{count},{value}}}" for count, value in runs[offset:offset + 8]) + ",")
    lines += ["}};", "inline const std::array<uint8_t,kEternalUi2AtlasWidth*kEternalUi2AtlasHeight>& eternalUi2AtlasPixels() {",
              "    static const auto pixels=[] {",
              "        std::array<uint8_t,kEternalUi2AtlasWidth*kEternalUi2AtlasHeight> result{}; size_t offset=0;",
              "        for(const auto& run:kEternalUi2CoverageRuns) { std::fill_n(result.begin()+offset,run.count,run.value); offset+=run.count; }",
              "        return result;",
              "    }(); return pixels;", "}", ""]
    report = {"font": str(FONT.relative_to(ROOT)), "sha256": font_hash, "family": font.getname(),
              "font_size": SIZE, "ascent": ascent, "descent": descent, "line_height": ascent + descent,
              "atlas": [WIDTH, HEIGHT], "coverage_runs": len(runs), "rle_payload_bytes": len(runs) * 3,
              "nonzero_pixels": sum(value != 0 for value in data), "atlas_sha256": hashlib.sha256(data).hexdigest(),
              "pillow": pillow_version, "freetype": features.version_module("freetype2")}
    return "\n".join(lines), atlas, report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    generated, atlas, report = bake()
    if args.verify:
        assert HEADER.read_text(encoding="utf-8") == generated, "Native Eternal UI 2 atlas is stale"
    else:
        HEADER.write_text(generated, encoding="utf-8", newline="\n")
    if args.preview:
        args.preview.parent.mkdir(parents=True, exist_ok=True)
        atlas.save(args.preview)
        args.preview.with_suffix(".json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report))


if __name__ == "__main__":
    main()
